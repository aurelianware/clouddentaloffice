using Microsoft.EntityFrameworkCore;

namespace CloudDentalOffice.Portal.Data;

/// <summary>
/// Adds the practice billing profile table to PostgreSQL databases provisioned
/// with EnsureCreated before it existed (EnsureCreated never adds tables to an
/// existing database). Mirrors the AddPracticeBillingProfiles migration.
/// </summary>
public static class PracticeBillingProfileSchemaReconciliation
{
    public static async Task ApplyAsync(
        CloudDentalDbContext dbContext,
        string databaseProvider,
        ILogger logger,
        CancellationToken cancellationToken = default)
    {
        if (!string.Equals(databaseProvider, "PostgreSQL", StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        const string sql = """
            CREATE TABLE IF NOT EXISTS "PracticeBillingProfiles" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY,
                "TenantId" character varying(64) NOT NULL,
                "LegalName" character varying(60) NOT NULL,
                "Npi" character varying(10) NOT NULL,
                "TaxId" character varying(9) NOT NULL,
                "TaxonomyCode" character varying(10) NOT NULL,
                "Address1" character varying(55) NOT NULL,
                "Address2" character varying(55),
                "City" character varying(30) NOT NULL,
                "State" character varying(2) NOT NULL,
                "ZipCode" character varying(9) NOT NULL,
                "ContactName" character varying(60) NOT NULL,
                "Phone" character varying(10) NOT NULL,
                "UpdatedAt" timestamp with time zone NOT NULL,
                "UpdatedBy" character varying(200),
                CONSTRAINT "PK_PracticeBillingProfiles" PRIMARY KEY ("Id")
            );

            CREATE UNIQUE INDEX IF NOT EXISTS "IX_PracticeBillingProfiles_TenantId"
                ON "PracticeBillingProfiles" ("TenantId");
            """;

        await dbContext.Database.ExecuteSqlRawAsync(sql, cancellationToken);
        logger.LogInformation("Practice billing profile schema reconciliation completed");
    }
}
